def _norm_waf(waf: Optional[str]) -> Optional[str]:
    if not waf:
        return None
    k = str(waf).strip().lower()
    if k in WAF_KEYS:
        return k
    aliases = {
        "cloud flare": "cloudflare", "cf": "cloudflare",
        "data dome": "datadome", "dd": "datadome",
        "imperva incapsula": "imperva", "incapsula": "imperva",
        "mod_security": "modsecurity", "modsec": "modsecurity",
        "f5 asm": "f5", "bigip": "f5", "big-ip": "f5",
    }
    return aliases.get(k)


def get_payloads(
    vuln_type: str,
    waf: Optional[str] = None,
    count: int = 0,
) -> Tuple[Dict[str, Any], Optional[str]]:
    """Return (result, error). count=0 means 'all'."""
    vt = (vuln_type or "").strip().lower()
    if vt not in PAYLOADS:
        return {}, (
            f"Unknown vuln_type '{vuln_type}'. Available: {', '.join(VULN_TYPES)}"
        )

    base = list(PAYLOADS[vt])
    wk = _norm_waf(waf)
    extra = WAF_EXTRA.get(wk, {}).get(vt, []) if wk else []
    allp = base + list(extra)

    total = len(allp)
    if count and count > 0:
        allp = allp[:count]

    result: Dict[str, Any] = {
        "vuln_type": vt,
        "waf": wk,
        "waf_targeted": bool(extra),
        "total_available": total,
        "returned": len(allp),
        "payloads": allp,
    }
    return result, None


